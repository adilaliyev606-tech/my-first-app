import random

# 1. Компьютер загадывает случайное число от 1 to 10
secret_number = random.randint(1, 10)

print("Я загадал число от 1 до 10. Попробуй угадать его!")

# 2. Запускаем бесконечный цикл, пока игрок не угадает
while True:
    # Просим пользователя ввести число
    user_guess = int(input("Введите ваше число: "))

    # 3. Проверяем условия
    if user_guess < secret_number:
        print("Слишком мало! Попробуй еще раз.")
    elif user_guess > secret_number:
        print("Слишком много! Попробуй еще раз.")
    else:
        print("Ура! Вы угадали число!")
        break  # Останавливаем игру и выходим из цикла
